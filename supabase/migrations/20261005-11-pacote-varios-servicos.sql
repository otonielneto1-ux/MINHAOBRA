-- Pacote com vários serviços, MO profissional/ajudante por serviço e colaboradores escolhidos
-- (pedido do Otoniel, 05/10/2026). Decisões:
--   * cada serviço do pacote tem a sua meta; o pacote só conclui quando TODOS batem a meta;
--   * MO profissional e MO ajudante em R$ por serviço; MO total = soma; prêmio do pacote = soma das MO totais;
--   * a parte profissional vai para os profissionais e a parte ajudante para os serventes (funcao = 'Servente'),
--     cada uma dividida pelos dias de presença no pacote;
--   * só os colaboradores escolhidos recebem, e o efetivo só lança o pacote para eles (terceirizado não entra).

-- 1. Tabelas novas.
create table public.pacote_servicos (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  pacote_id bigint not null references public.pacotes (id) on delete cascade,
  servico_id bigint not null references public.servicos (id),
  quantidade_meta numeric(14,3) not null check (quantidade_meta > 0),
  quantidade_executada numeric(14,3) not null default 0,
  mo_profissional numeric(14,2) not null default 0 check (mo_profissional >= 0),
  mo_ajudante numeric(14,2) not null default 0 check (mo_ajudante >= 0),
  mo_total numeric(14,2) generated always as (mo_profissional + mo_ajudante) stored,
  created_at timestamptz not null default now(),
  unique (pacote_id, servico_id)
);
create index pacote_servicos_servico_idx on public.pacote_servicos (servico_id);

create table public.pacote_colaboradores (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  pacote_id bigint not null references public.pacotes (id) on delete cascade,
  funcionario_id bigint not null references public.funcionarios (id),
  created_at timestamptz not null default now(),
  unique (pacote_id, funcionario_id)
);

-- 2. Os pacotes que já existem passam para o formato novo (o prêmio vira MO profissional; ninguém perde dado)
--    e quem já trabalhou num pacote vira colaborador dele.
insert into public.pacote_servicos (obra_id, pacote_id, servico_id, quantidade_meta, quantidade_executada, mo_profissional, mo_ajudante)
select obra_id, id, servico_id, quantidade_meta, quantidade_executada, valor_premio, 0 from public.pacotes;

insert into public.pacote_colaboradores (obra_id, pacote_id, funcionario_id)
select distinct pr.obra_id, pr.pacote_id, pr.funcionario_id
  from public.presencas pr join public.funcionarios f on f.id = pr.funcionario_id
 where pr.pacote_id is not null and f.tipo_mao_obra <> 'Terceirizada';

-- 3. Saem do pacote os campos que agora moram em pacote_servicos (antes, as regras que dependem deles).
