drop policy pacotes_editar on public.pacotes;
drop function public.pacotes_sem_premio(bigint);
alter table public.pacotes drop column servico_id, drop column quantidade_meta, drop column quantidade_executada, drop column valor_premio;

-- 4. Regras de acesso.
--    Pacote: à mão só Planejado / Liberado / Em execução; Concluído, Não concluído e fechado_em saem do fechamento.
create policy pacotes_criar on public.pacotes for insert
  with check (obra_id in (select minhas_obras()) and (select papel_em(array['Engenheiro', 'Coordenador']))
    and status in ('Planejado', 'Liberado', 'Em execução') and fechado_em is null);
create policy pacotes_editar on public.pacotes for update
  using (obra_id in (select minhas_obras()) and fechado_em is null and (select papel_em(array['Engenheiro', 'Coordenador'])))
  with check (obra_id in (select minhas_obras()) and (select papel_em(array['Engenheiro', 'Coordenador']))
    and status in ('Planejado', 'Liberado', 'Em execução') and fechado_em is null);

--    Serviços do pacote (têm dinheiro: só Engenheiro e Coordenador; o Mestre lê pela função sem MO).
alter table public.pacote_servicos enable row level security;
create policy pacote_servicos_ver on public.pacote_servicos for select
  using (obra_id in (select minhas_obras()) and (select papel_em(array['Engenheiro', 'Coordenador'])));
create policy pacote_servicos_criar on public.pacote_servicos for insert
  with check (obra_id in (select minhas_obras()) and (select papel_em(array['Engenheiro', 'Coordenador'])) and quantidade_executada = 0
    and exists (select 1 from pacotes p where p.id = pacote_id and p.obra_id = pacote_servicos.obra_id and p.fechado_em is null)
    and exists (select 1 from servicos s where s.id = servico_id and s.obra_id = pacote_servicos.obra_id and not s.e_resumo));
create policy pacote_servicos_editar on public.pacote_servicos for update
  using (obra_id in (select minhas_obras()) and (select papel_em(array['Engenheiro', 'Coordenador']))
    and exists (select 1 from pacotes p where p.id = pacote_id and p.fechado_em is null));
create policy pacote_servicos_apagar on public.pacote_servicos for delete
  using (obra_id in (select minhas_obras()) and (select papel_em(array['Engenheiro', 'Coordenador'])) and quantidade_executada = 0
    and exists (select 1 from pacotes p where p.id = pacote_id and p.fechado_em is null));
-- A quantidade executada é do gatilho: pelo navegador só se mudam meta e MO.
