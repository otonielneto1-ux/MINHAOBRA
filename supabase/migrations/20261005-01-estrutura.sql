-- ── Equipe ───────────────────────────────────────────────────
create table public.funcionarios (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  nome text not null,
  funcao text not null check (funcao in ('Servente', 'Pedreiro', 'Carpinteiro', 'Armador', 'Encanador', 'Eletricista', 'Operador de máquina', 'Motorista', 'Encarregado', 'Apontador', 'Almoxarife', 'Técnico', 'Outro')),
