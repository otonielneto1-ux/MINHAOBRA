-- ── Pacotes ──────────────────────────────────────────────────
create table public.pacotes (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  servico_id bigint not null references public.servicos (id),
  nome text not null,
  local text not null,
  quantidade_meta numeric(14,3) not null check (quantidade_meta > 0),
  quantidade_executada numeric(14,3) not null default 0,
  valor_premio numeric(14,2) not null,
  data_inicio date not null,
  data_fechamento date not null,
  status text not null default 'Planejado' check (status in ('Planejado', 'Liberado', 'Em execução', 'Concluído', 'Não concluído')),
  motivo_nao_conclusao text check (motivo_nao_conclusao in ('Chuva', 'Falta de material', 'Falta de equipe', 'Projeto', 'Equipamento', 'Frente não liberada', 'Outro')),
  fechado_em timestamptz,
  created_at timestamptz not null default now(),
  check (status <> 'Não concluído' or motivo_nao_conclusao is not null)
);

create table public.presencas (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  data date not null,
  funcionario_id bigint not null references public.funcionarios (id),
  situacao text not null check (situacao in ('Presente', 'Falta', 'Atestado', 'Afastado')),
  pacote_id bigint references public.pacotes (id),
  lancado_por bigint not null references public.profiles (id),
  created_at timestamptz not null default now(),
  unique (funcionario_id, data),
  check (situacao = 'Presente' or pacote_id is null)
);
create index on public.presencas (obra_id, data);

create table public.premios (
  id bigint generated by default as identity primary key,
  pacote_id bigint not null references public.pacotes (id) on delete cascade,
  funcionario_id bigint not null references public.funcionarios (id),
  dias smallint not null,
  valor numeric(14,2) not null,
  created_at timestamptz not null default now()
);

-- ── PCP ──────────────────────────────────────────────────────
create table public.pcp_atividades (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  semana_inicio date not null check (extract(isodow from semana_inicio) = 1),
  data_prevista date not null,
  servico_id bigint not null references public.servicos (id),
  pacote_id bigint references public.pacotes (id),
  local text not null,
  quantidade_planejada numeric(14,3) not null check (quantidade_planejada > 0),
  equipe text,
  status text not null default 'Planejada' check (status in ('Planejada', 'Concluída', 'Não concluída')),
  quantidade_executada numeric(14,3),
  motivo_nao_conclusao text check (motivo_nao_conclusao in ('Chuva', 'Falta de material', 'Falta de equipe', 'Projeto', 'Equipamento', 'Frente não liberada', 'Outro')),
  baixa_por bigint references public.profiles (id),
  baixa_em timestamptz,
  copiada_de_id bigint references public.pcp_atividades (id),
  created_at timestamptz not null default now(),
  check (data_prevista between semana_inicio and semana_inicio + 5),
  check (status <> 'Não concluída' or motivo_nao_conclusao is not null)
);
create index on public.pcp_atividades (obra_id, semana_inicio);
create index on public.pcp_atividades (obra_id, data_prevista);

create table public.producoes (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  data date not null,
  servico_id bigint not null references public.servicos (id),
  quantidade numeric(14,3) not null,
  origem text not null check (origem in ('PCP', 'Ajuste')),
  pcp_atividade_id bigint unique references public.pcp_atividades (id) on delete cascade,
  pacote_id bigint references public.pacotes (id),
  motivo_ajuste text,
  lancado_por bigint not null references public.profiles (id),
  created_at timestamptz not null default now(),
  check (origem <> 'PCP' or pcp_atividade_id is not null),
  check (origem <> 'Ajuste' or motivo_ajuste is not null),
  check (origem = 'Ajuste' or quantidade >= 0)
);
create index on public.producoes (servico_id, data);

