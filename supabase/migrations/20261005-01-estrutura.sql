-- ── Pessoas ──────────────────────────────────────────────────
create table public.profiles (
  id bigint generated by default as identity primary key,
  -- vazio só nas pessoas de exemplo (sem login); quem se cadastra sempre tem
  auth_uid uuid unique references auth.users (id) on delete cascade,
  nome text not null default '',
  email text not null unique,
  role text not null default 'Aguardando' check (role in ('Aguardando', 'Engenheiro', 'Coordenador', 'Mestre', 'Cliente', 'Técnico de Segurança', 'Auxiliar Administrativo')),
  ativo boolean not null default true,
  created_at timestamptz not null default now()
);

-- ── Configuração geral (uma linha) ───────────────────────────
create table public.config (
  id int primary key default 1 check (id = 1),
  nome_construtora text not null,
  logo_construtora text,
  created_at timestamptz not null default now()
);

-- ── Obra ─────────────────────────────────────────────────────
create table public.obras (
  id bigint generated by default as identity primary key,
  nome text not null,
  cidade text not null,
  uf text not null,
  cliente text not null,
  data_inicio date not null,
  data_fim_contrato date not null,
  dia_fechamento_folha smallint not null check (dia_fechamento_folha between 1 and 31),
  status text not null default 'Em andamento' check (status in ('Em andamento', 'Paralisada', 'Concluída')),
  ultimo_calculo_em timestamptz,
  foto_obra text,
  logo_cliente text,
  created_at timestamptz not null default now()
);

create table public.obra_usuarios (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  profile_id bigint not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (obra_id, profile_id)
);

create table public.etapas_entrega (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  nome text not null,
  ordem smallint not null,
  data_entrega_contratual date,
  created_at timestamptz not null default now(),
  unique (obra_id, nome)
);

-- ── Cronograma ───────────────────────────────────────────────
create table public.servicos (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  uid_project int not null,
  pai_id bigint references public.servicos (id),
  etapa_entrega_id bigint references public.etapas_entrega (id),
  codigo_eap text not null,
  nome text not null,
  nivel smallint not null,
  e_resumo boolean not null default false,
  local text,
  unidade text not null default '%' check (unidade in ('%', 'm', 'm²', 'm³', 'kg', 't', 'un')),
  quantidade_prevista numeric(14,3) not null default 100 check (quantidade_prevista > 0),
  custo_orcado numeric(14,2),
  unidade_alterada_em timestamptz,
  inicio_previsto date not null,
  fim_previsto date not null,
  duracao_dias int not null,
  inicio_base date,
  fim_base date,
  inicio_cedo date,
  fim_tarde date,
  folga_dias int,
  critico boolean not null default false,
  quantidade_executada numeric(14,3) not null default 0,
  inicio_real date,
  fim_real date,
  dias_atraso int not null default 0,
  cancelado boolean not null default false,
  created_at timestamptz not null default now(),
  unique (obra_id, uid_project)
);
create index on public.servicos (obra_id, codigo_eap);
create index on public.servicos (obra_id, etapa_entrega_id);

create table public.servico_dependencias (
  id bigint generated by default as identity primary key,
  servico_id bigint not null references public.servicos (id) on delete cascade,
  predecessora_id bigint not null references public.servicos (id) on delete cascade,
  tipo text not null check (tipo in ('TI', 'II', 'TT', 'IT')),
  defasagem_dias int not null default 0,
  created_at timestamptz not null default now(),
  unique (servico_id, predecessora_id),
  check (servico_id <> predecessora_id)
);

create table public.restricoes (
  id bigint generated by default as identity primary key,
  obra_id bigint not null references public.obras (id) on delete cascade,
  servico_id bigint not null references public.servicos (id) on delete cascade,
  tipo text not null check (tipo in ('Material', 'Projeto', 'Equipe', 'Equipamento', 'Liberação de área', 'Segurança', 'Outro')),
  descricao text not null,
  responsavel text,
  data_limite date,
  status text not null default 'Pendente' check (status in ('Pendente', 'Removida')),
  removida_em date,
  created_at timestamptz not null default now(),
  check (status <> 'Removida' or removida_em is not null)
