-- ── Gatilhos ─────────────────────────────────────────────────
-- Cadastro: toda conta nova vira um perfil "Aguardando".
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (auth_uid, nome, email, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'nome', ''), new.email, 'Aguardando');
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Produção → quantidade executada, início e fim real do serviço, e do pacote ainda aberto.
create or replace function public.recalcular_executado()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  sid bigint := coalesce(new.servico_id, old.servico_id);
  pids bigint[] := array_remove(array[new.pacote_id, old.pacote_id], null);
begin
  update servicos s set
    quantidade_executada = coalesce(t.soma, 0),
    inicio_real = t.primeira,
    fim_real = case when coalesce(t.soma, 0) >= s.quantidade_prevista then coalesce(s.fim_real, t.ultima) end
  from (select sum(quantidade) soma, min(data) filter (where quantidade > 0) primeira, max(data) ultima
        from producoes where servico_id = sid) t
  where s.id = sid;
  update pacotes p set quantidade_executada = coalesce((select sum(quantidade) from producoes where pacote_id = p.id), 0)
  where p.id = any (pids) and p.fechado_em is null;
  return null;
end;
$$;
create trigger producoes_recalcular after insert or update or delete on public.producoes
  for each row execute function public.recalcular_executado();

-- Ocorrência: número sequencial por obra.
create or replace function public.numerar_ocorrencia()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  new.numero := coalesce((select max(numero) from ocorrencias where obra_id = new.obra_id), 0) + 1;
  return new;
end;
$$;
create trigger ocorrencias_numerar before insert on public.ocorrencias
  for each row execute function public.numerar_ocorrencia();
